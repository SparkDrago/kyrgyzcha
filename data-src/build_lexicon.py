entries = collections.OrderedDict()   # key -> {w, g:[...], p, s:set}
def add(w, gloss, pos, src):
    w = w.strip()
    if not w: return
    k = w
    e = entries.get(k)
    if not e:
        e = entries[k] = {'w': w, 'g': [], 'p': POSN.get(pos, pos or ''), 's': []}
    for g in re.split(r'\s*;\s*', gloss):
        g = g.strip()
        if g and g.lower() not in [x.lower() for x in e['g']]: e['g'].append(g)
    if src not in e['s']: e['s'].append(src)
    if not e['p'] and pos: e['p'] = POSN.get(pos, pos)

for w, en, pos, topic, pic in KC: add(w, en, pos, 'kc')
for w, en, pos, topic, pic in PC: add(w, en, pos, 'pc')
for w, (pos, gl) in W.items(): add(w, gl, pos, 'wk')

rows = []
for e in entries.values():
    g = '; '.join(e['g'])
    if len(g) > 140: g = g[:137].rsplit(' ', 1)[0] + '…'
    rows.append([e['w'], g, e['p'], ','.join(e['s'])])
rows.sort(key=lambda r: r[0].lower())

