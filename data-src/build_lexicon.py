def load(f):
    out = []
    for l in open(f, encoding='utf-8'):
        p = l.rstrip('\n').split('\t')
        if len(p) >= 3 and p[0].strip():
            p += [''] * (5 - len(p)); out.append([x.strip() for x in p[:5]])
    return out
